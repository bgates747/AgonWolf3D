from contextlib import contextmanager
import os
from pathlib import Path
import tempfile


def _section_markers(section_name):
    begin_marker = f"; #### AUTOGENERATED {section_name} BEGIN ####"
    end_marker = f"; #### AUTOGENERATED {section_name} END ####"
    return begin_marker, end_marker


def replace_asm_section(asm_path, section_name, generated_content):
    """Replace exactly one marked section without disturbing its neighbors."""
    asm_path = Path(asm_path)
    original = asm_path.read_text(encoding="utf-8")
    begin_marker, end_marker = _section_markers(section_name)

    if original.count(begin_marker) != 1:
        raise ValueError(
            f"{asm_path} must contain exactly one {begin_marker!r} marker"
        )
    if original.count(end_marker) != 1:
        raise ValueError(
            f"{asm_path} must contain exactly one {end_marker!r} marker"
        )

    before, remainder = original.split(begin_marker, 1)
    old_content, after = remainder.split(end_marker, 1)
    del old_content

    generated_content = generated_content.rstrip("\n")
    replacement = begin_marker
    if generated_content:
        replacement += f"\n{generated_content}\n"
    else:
        replacement += "\n"
    replacement += end_marker

    updated = before + replacement + after
    asm_path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=asm_path.parent,
        prefix=f".{asm_path.name}.",
        delete=False,
    ) as writer:
        temporary_path = Path(writer.name)
        writer.write(updated)

    try:
        os.chmod(temporary_path, 0o644)
        os.replace(temporary_path, asm_path)
    finally:
        temporary_path.unlink(missing_ok=True)


@contextmanager
def generated_asm_section(asm_path, section_name):
    """Yield a temporary legacy output path, then install it into one section."""
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        prefix=f"agonwolf3d_{section_name.lower()}_",
        suffix=".asm",
        delete=False,
    ) as writer:
        temporary_path = Path(writer.name)

    try:
        yield str(temporary_path)
        generated_content = temporary_path.read_text(encoding="utf-8")
        replace_asm_section(asm_path, section_name, generated_content)
    finally:
        temporary_path.unlink(missing_ok=True)
